import { spawn } from 'node:child_process';
import { writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { check, ok, done } from './check.mjs';
const [,, base, outDir] = process.argv;
const chrome = spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  ['--headless=new', '--remote-debugging-port=9336', '--user-data-dir=' + mkdtempSync(tmpdir() + '/chr-'), '--no-first-run', 'about:blank'], { stdio: 'ignore' });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let ws; for (let i = 0; i < 40; i++) { try { const l = await (await fetch('http://127.0.0.1:9336/json/list')).json(); const p = l.find((x) => x.type === 'page'); if (p) { ws = p.webSocketDebuggerUrl; break; } } catch {} await sleep(250); }
const sock = new WebSocket(ws); await new Promise((r) => (sock.onopen = r));
let id = 0; const pending = new Map();
sock.onmessage = (m) => { const d = JSON.parse(m.data); if (d.id && pending.has(d.id)) { pending.get(d.id)(d); pending.delete(d.id); } };
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pending.set(i, r); sock.send(JSON.stringify({ id: i, method, params })); });
const js = async (expr) => (await send('Runtime.evaluate', { expression: expr, awaitPromise: true, returnByValue: true })).result?.result?.value;
const shot = async (name) => { await js('document.fonts.ready.then(()=>1)'); const r = await send('Page.captureScreenshot', { format: 'png' }); writeFileSync(`${outDir}/${name}.png`, Buffer.from(r.result.data, 'base64')); };
const type = (sel, v) => js(`(() => { const el = document.querySelector('${sel}'); el.value = ${JSON.stringify(v)}; el.dispatchEvent(new Event('input', { bubbles: true })); return true; })()`);
const click = (sel) => js(`(() => { const el = document.querySelector('${sel}'); if (!el) return 'NOT FOUND'; el.click(); return true; })()`);
const text = (sel) => js(`document.querySelector('${sel}')?.textContent.trim()`);
const all = (sel) => js(`[...document.querySelectorAll('${sel}')].map(e => e.textContent.trim())`);
await send('Page.enable'); await send('Runtime.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 2, mobile: true });
await send('Page.navigate', { url: base + '/login' }); await sleep(2500);
await type('#login-email', 'alice@family.home'); await type('#login-password', 'correct-password1');
await click('button[type=submit]'); await sleep(2000);
await click('a[href="/categories"]'); await sleep(1500);
// 兩筆種子分類在同一毫秒建立，排序落到隨機的 id 上，每次跑順序可能不同（正式資料庫建立後順序固定）：不檢查先後
const pairsOf = async () => { const n = await all('.list__name'); const sub = await all('.list__sub'); return n.map((x, i) => `${x}｜${sub[i]}`).sort(); };
check('1 分類列表與說明（種子 2 筆，不比先後）', await pairsOf(), ['蔬菜｜0 項商品 · 沒有自訂欄位', '衛生紙｜1 項商品 · 3 個自訂欄位'].sort());
await type('#category-new', '衛生紙'); await click('form.add button[type=submit]'); await sleep(1000);
check('2 重複名稱 → ERR-003', await text('#category-new-error'), '此分類名稱已存在，請使用其他名稱');
await type('#category-new', '清潔用品'); await click('form.add button[type=submit]'); await sleep(1200);
const afterAdd = await all('.list__name');
check('3 新增清潔用品 → 排在最後、MSG-001', [afterAdd.at(-1), afterAdd.slice(0, 2).sort(), await text('.q-notification')], ['清潔用品', ['蔬菜', '衛生紙'].sort(), '分類建立成功']);
await shot('cat-1-list');
await js(`[...document.querySelectorAll('.list__row')].find(r => r.textContent.includes('衛生紙')).click(); true`); await sleep(1500);
ok('4 編輯衛生紙的網址', /^\/categories\/\w+\/edit$/.test(await js('location.pathname')), await js('location.pathname'));
check('4 欄位、刪除停用與原因（ERR-004 的提前說明）', [await all('.fields__name'), await js(`document.querySelector('.danger__button').disabled`), await text('.danger__hint')], [['抽數(單包)', '包數', '層數'], true, '此分類下仍有 1 項商品，要先刪除或移走商品']);
await shot('cat-2-edit');
await js(`[...document.querySelectorAll('.fields__open')][0].click(); true`); await sleep(800);
check('5 已使用的欄位：鎖定說明、不能刪除', [await text('.sheet h2'), await text('.sheet [role=note]'), await js(`document.querySelector('.sheet__delete').disabled`)], ['編輯欄位', '已有 1 筆購買記錄使用這個欄位，只能修改名稱與順序；型別與計算方式不能改，也不能刪除。', true]);
await shot('cat-3-sheet-locked');
await click('.sheet__cancel'); await sleep(800);
await click('button[aria-label="上移「層數」"]'); await sleep(1200);
check('6 層數上移', await all('.fields__name'), ['抽數(單包)', '層數', '包數']);
await send('Page.navigate', { url: base + '/categories' }); await sleep(1500);
await js(`[...document.querySelectorAll('.list__row')].find(r => r.textContent.includes('蔬菜')).click(); true`); await sleep(1500);
await click('.danger__button'); await sleep(800);
check('7 刪除蔬菜 → CONFIRM-003', await text('.q-dialog .q-card__section'), '確定要刪除分類「蔬菜」嗎？');
await shot('cat-4-confirm');
await js(`[...document.querySelectorAll('.q-dialog button')].find(b => b.textContent.includes('刪除')).click(); true`); await sleep(1500);
check('8 刪除後回列表', [await js('location.pathname'), await all('.list__name')], ['/categories', ['衛生紙', '清潔用品']]);
sock.close(); chrome.kill();
done();
